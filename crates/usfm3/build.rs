//! Generates per-version `MarkerTable`s from `data/markers.toml` into
//! `$OUT_DIR/marker_tables.rs`, which `marker.rs` includes. Each version gets a
//! `&[MarkerInfo]` slice plus a `phf` perfect-hash `name -> id` map.

use std::collections::{BTreeMap, HashSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde::Deserialize;

#[derive(Deserialize)]
struct Spec {
    groups: BTreeMap<String, Group>,
}

#[derive(Deserialize)]
struct Group {
    category: String,
    role: Option<String>,
    closing: Option<String>,
    usx: Option<String>,
    since: Option<String>,
    until: Option<String>,
    /// First version in which these markers are deprecated (still valid, but
    /// advised against), e.g. "3.0". Pairs with `deprecated_for`.
    deprecated_since: Option<String>,
    /// Replacement guidance shown in the `DeprecatedMarker` advisory.
    deprecated_for: Option<String>,
    names: Vec<String>,
}

struct Marker {
    name: String,
    category: &'static str,
    role: &'static str,
    closing: &'static str,
    usx: String,
    since: u32,
    until: Option<u32>,
    deprecated_since: Option<u32>,
    deprecated_for: Option<String>,
}

/// USFM versions we emit a table for: (Rust `Version` variant, minor rank).
const VERSIONS: &[(&str, u32)] = &[("V3_1", 1), ("V3_2", 2)];

fn main() {
    println!("cargo:rerun-if-changed=data/markers.toml");
    println!("cargo:rerun-if-changed=build.rs");

    let toml_src = fs::read_to_string("data/markers.toml").expect("read data/markers.toml");
    let spec: Spec = toml::from_str(&toml_src).expect("parse data/markers.toml");

    // Flatten groups (BTreeMap → deterministic order) into one marker list.
    let mut markers: Vec<Marker> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();
    for (gid, g) in &spec.groups {
        let category = category_variant(&g.category, gid);
        let role = match &g.role {
            Some(r) => role_variant(r, gid),
            None => default_role(&g.category),
        };
        let closing = match &g.closing {
            Some(c) => closing_variant(c, gid),
            None => default_closing(&g.category),
        };
        let usx = g
            .usx
            .clone()
            .unwrap_or_else(|| default_usx(&g.category).to_string());
        let since = ver_rank(g.since.as_deref().unwrap_or("3.0"));
        let until = g.until.as_deref().map(ver_rank);
        let deprecated_since = g.deprecated_since.as_deref().map(ver_rank);
        if deprecated_since.is_some() && g.deprecated_for.is_none() {
            panic!("group `{gid}`: `deprecated_since` requires `deprecated_for`");
        }
        for name in &g.names {
            if !seen.insert(name.clone()) {
                panic!("marker `{name}` appears in more than one group (group `{gid}`)");
            }
            markers.push(Marker {
                name: name.clone(),
                category,
                role,
                closing,
                usx: usx.clone(),
                since,
                until,
                deprecated_since,
                deprecated_for: g.deprecated_for.clone(),
            });
        }
    }

    let mut code = String::new();
    code.push_str("// @generated by build.rs from data/markers.toml — do not edit.\n");

    for (variant, rank) in VERSIONS {
        let filtered: Vec<&Marker> = markers
            .iter()
            .filter(|m| m.since <= *rank && m.until.is_none_or(|u| *rank <= u))
            .collect();

        // Entries slice.
        writeln!(code, "static {variant}_ENTRIES: &[MarkerInfo] = &[").unwrap();
        for m in &filtered {
            // Deprecation is version-aware: only flagged once this table's version
            // reaches the marker's `deprecated_since`.
            let deprecated = match (m.deprecated_since, &m.deprecated_for) {
                (Some(since), Some(repl)) if *rank >= since => format!("Some({repl:?})"),
                _ => "None".to_string(),
            };
            writeln!(
                code,
                "    MarkerInfo {{ name: {:?}, category: Category::{}, text_role: TextRole::{}, closing: Closing::{}, usx_element: {:?}, deprecated: {} }},",
                m.name, m.category, m.role, m.closing, m.usx, deprecated
            )
            .unwrap();
        }
        code.push_str("];\n");

        // phf name -> index map.
        let mut builder = phf_codegen::Map::new();
        for (i, m) in filtered.iter().enumerate() {
            builder.entry(m.name.as_str(), &format!("{i}u16"));
        }
        writeln!(
            code,
            "static {variant}_INDEX: ::phf::Map<&'static str, u16> = {};",
            builder.build()
        )
        .unwrap();

        writeln!(
            code,
            "pub static {variant}_TABLE: MarkerTable = MarkerTable {{ entries: {variant}_ENTRIES, index: &{variant}_INDEX }};\n"
        )
        .unwrap();
    }

    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("marker_tables.rs");
    fs::write(&out, code).expect("write marker_tables.rs");
}

fn ver_rank(v: &str) -> u32 {
    v.rsplit('.')
        .next()
        .and_then(|s| s.parse().ok())
        .unwrap_or(0)
}

fn category_variant(c: &str, gid: &str) -> &'static str {
    match c {
        "identification" => "Identification",
        "chapter" => "Chapter",
        "verse" => "Verse",
        "paragraph" => "Paragraph",
        "character" => "Character",
        "note" => "Note",
        "milestone" => "Milestone",
        "other" => "Other",
        _ => panic!("group `{gid}`: unknown category `{c}`"),
    }
}

fn role_variant(r: &str, gid: &str) -> &'static str {
    match r {
        "content" => "Content",
        "excluded" => "Excluded",
        "boundary" => "Boundary",
        _ => panic!("group `{gid}`: unknown role `{r}`"),
    }
}

fn closing_variant(c: &str, gid: &str) -> &'static str {
    match c {
        "none" => "None",
        "optional" => "Optional",
        "required" => "Required",
        _ => panic!("group `{gid}`: unknown closing `{c}`"),
    }
}

fn default_role(category: &str) -> &'static str {
    match category {
        "character" => "Content",
        "note" => "Excluded",
        "paragraph" => "Boundary",
        "identification" => "Excluded",
        "chapter" | "verse" => "Boundary",
        "milestone" => "Excluded",
        _ => "Content",
    }
}

fn default_closing(category: &str) -> &'static str {
    match category {
        "character" | "note" => "Required",
        _ => "None",
    }
}

fn default_usx(category: &str) -> &'static str {
    match category {
        "identification" | "paragraph" => "para",
        "character" => "char",
        "note" => "note",
        "chapter" => "chapter",
        "verse" => "verse",
        "milestone" => "ms",
        _ => "char",
    }
}
